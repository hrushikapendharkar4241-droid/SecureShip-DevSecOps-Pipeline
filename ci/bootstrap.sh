#!/usr/bin/env bash
# One-command setup of the free SecureShip lab:
#   1. generates ci/.env with random passwords + ledger HMAC key
#   2. generates the deploy SSH key pair (ci/keys/)
#   3. starts SonarQube, sets a strong admin password and creates an analysis token
#   4. builds and starts Jenkins (configured as code) and the lab deployment target
#
# Usage:  ./ci/bootstrap.sh
#         SECURESHIP_REPO_URL=https://github.com/<you>/SecureShip-DevSecOps-Pipeline.git ./ci/bootstrap.sh
# Works on Linux, macOS, WSL2 and Git Bash (Windows) with Docker Desktop running.
set -euo pipefail

CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$CI_DIR"
ENV_FILE="$CI_DIR/.env"
SONAR_URL="http://localhost:9000"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }
rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-32}"; }
set_env() {  # set_env KEY VALUE  (portable in-place edit)
  local tmp; tmp="$(mktemp)"
  grep -v "^$1=" "$ENV_FILE" > "$tmp" || true
  printf '%s=%s\n' "$1" "$2" >> "$tmp"
  cat "$tmp" > "$ENV_FILE"; rm -f "$tmp"
}
get_env() { grep "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- || true; }

command -v docker >/dev/null || fail "Docker is not installed"
docker info >/dev/null 2>&1 || fail "Docker is not running – start Docker Desktop"
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required"
command -v curl >/dev/null || fail "curl is required"
command -v ssh-keygen >/dev/null || fail "ssh-keygen is required (Git Bash / OpenSSH)"

# First run only: check disk, RAM, ports, repos and the ShopPilot /health endpoint before
# downloading gigabytes. SKIP_PREFLIGHT=1 skips it.
if [ ! -f "$ENV_FILE" ] && [ "${SKIP_PREFLIGHT:-0}" != "1" ]; then
  "$CI_DIR/preflight.sh" || fail "pre-flight check failed – fix the FAIL lines above (or SKIP_PREFLIGHT=1 to override)"
fi

# ---------------------------------------------------------------- 1. secrets
if [ ! -f "$ENV_FILE" ]; then
  say "Creating ci/.env with random secrets"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by ci/bootstrap.sh – local secrets for the SecureShip lab. NEVER commit this file.
JENKINS_ADMIN_ID=admin
JENKINS_ADMIN_PASSWORD=$(rand 20)
SONAR_ADMIN_PASSWORD=Ss1!$(rand 24)
SONAR_DB_PASSWORD=$(rand 28)
SONAR_TOKEN=
LEDGER_HMAC_KEY=$(rand 48)
SECURESHIP_REPO_URL=${SECURESHIP_REPO_URL:-https://github.com/hrushikapendharkar4241-droid/SecureShip-DevSecOps-Pipeline.git}
SECURESHIP_BRANCH=${SECURESHIP_BRANCH:-main}
APP_REPO_URL=${APP_REPO_URL:-https://github.com/hrushikapendharkar4241-droid/shoppilot.git}
EOF
fi

# ---------------------------------------------------------------- 1b. private ShopPilot repo
# Jenkins runs in a container without your GitHub login. If ShopPilot is private, it needs a
# read-only token (stored in ci/.env, which is git-ignored, and loaded as Jenkins credential
# 'shoppilot-git'). APP_GIT_TOKEN can also be passed as an environment variable.
app_repo="$(get_env APP_REPO_URL)"
anon_git() { GIT_TERMINAL_PROMPT=0 git -c credential.helper= "$@"; }
token_git() {  # token_git <user> <token> <git args...>  – token goes in a header, never in the URL
  local auth; auth="$(printf '%s:%s' "$1" "$2" | base64 | tr -d '\n')"; shift 2
  GIT_TERMINAL_PROMPT=0 git -c credential.helper= -c "http.extraHeader=Authorization: Basic $auth" "$@"
}
if [ -z "$(get_env APP_GIT_TOKEN)" ]; then
  if anon_git ls-remote --heads "$app_repo" >/dev/null 2>&1; then
    say "ShopPilot repository is public – Jenkins can clone it without a token"
  else
    owner="$(printf '%s' "$app_repo" | sed -E 's#https://github.com/([^/]+)/.*#\1#')"
    tok="${APP_GIT_TOKEN:-}"
    if [ -z "$tok" ] && [ -t 0 ]; then
      cat <<EOT

  ShopPilot ($app_repo) is PRIVATE, so Jenkins needs a read-only GitHub token to clone it.
  Create one (2 minutes): GitHub → Settings → Developer settings → Personal access tokens
  → Fine-grained tokens → Generate new token
      Repository access : Only select repositories → shoppilot
      Permissions       : Repository permissions → Contents → Read-only   (nothing else)
      Expiration        : 90 days
EOT
      read -rsp "  Paste the token here (input is hidden, Enter to skip): " tok || true; echo
    fi
    # Pasting in a Windows terminal can add spaces, CR or invisible characters – keep only token characters
    tok="$(printf '%s' "$tok" | LC_ALL=C tr -cd 'A-Za-z0-9_')"
    if [ -n "$tok" ]; then
      # ghs_ = a GitHub Actions job token (CI); username x-access-token is what GitHub expects for it
      case "$tok" in ghs_*) owner=x-access-token ;; esac
      case "$tok" in github_pat_*|ghp_*|ghs_*) ;; *)
        fail "That doesn't look like a GitHub token (it should start with github_pat_). Copy it again and rerun ./ci/bootstrap.sh";;
      esac
      echo "  Checking the token with GitHub (${#tok} characters, starts with ${tok:0:11}…)"
      if ! token_git "$owner" "$tok" ls-remote --heads "$app_repo" >/dev/null 2>&1; then
        fail "GitHub rejected the token for $app_repo. Check on GitHub → Fine-grained tokens that it is not expired, Resource owner = $owner, Repository access includes 'shoppilot', and Contents = Read-only. Then rerun ./ci/bootstrap.sh"
      fi
      set_env APP_GIT_USER "$owner"
      set_env APP_GIT_TOKEN "$tok"
      set_env APP_GIT_CREDENTIALS_ID shoppilot-git
      unset tok
      say "Token verified – Jenkins will use credential 'shoppilot-git' to clone ShopPilot"
    else
      printf '\033[1;33mWARNING:\033[0m no token given – the first build will fail at "Checkout".\n' >&2
      printf '         Rerun ./ci/bootstrap.sh later to add one.\n' >&2
    fi
  fi
fi

# ---------------------------------------------------------------- 2. SSH key
mkdir -p keys
if [ ! -f keys/deploy_ed25519 ]; then
  say "Generating deploy SSH key pair (ci/keys/)"
  ssh-keygen -t ed25519 -N "" -C "secureship-deploy" -f keys/deploy_ed25519 >/dev/null
fi
chmod 600 keys/deploy_ed25519 2>/dev/null || true

# ---------------------------------------------------------------- 3. SonarQube
say "Starting SonarQube (first start takes 1-3 minutes)"
docker compose up -d sonar-db sonarqube
for i in $(seq 1 90); do
  status="$(curl -fsS "$SONAR_URL/api/system/status" 2>/dev/null | sed -n 's/.*"status":"\([A-Z_]*\)".*/\1/p' || true)"
  [ "$status" = "UP" ] && break
  [ "$i" = 90 ] && fail "SonarQube did not become ready (last status: ${status:-none}). Check: docker logs secureship-sonarqube"
  sleep 4
done
say "SonarQube is UP"

if [ -z "$(get_env SONAR_TOKEN)" ]; then
  admin_pw="$(get_env SONAR_ADMIN_PASSWORD)"
  # Replace the default admin/admin password (ignored if it was already changed)
  curl -fsS -u admin:admin -X POST "$SONAR_URL/api/users/change_password" \
       --data-urlencode "login=admin" --data-urlencode "previousPassword=admin" \
       --data-urlencode "password=$admin_pw" >/dev/null 2>&1 || true
  say "Creating SonarQube analysis token for Jenkins"
  resp="$(curl -fsS -u "admin:$admin_pw" -X POST "$SONAR_URL/api/user_tokens/generate" \
          --data-urlencode "name=jenkins-$(date +%Y%m%d%H%M%S)")" \
    || fail "Could not create a Sonar token. If you changed the admin password manually, put it in SONAR_ADMIN_PASSWORD in ci/.env"
  token="$(printf '%s' "$resp" | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')"
  [ -n "$token" ] || fail "Unexpected response from SonarQube: $resp"
  set_env SONAR_TOKEN "$token"
fi

# ---------------------------------------------------------------- 4. Jenkins + target
say "Building and starting Jenkins and the lab deployment target"
docker compose up -d --build --force-recreate jenkins
docker compose up -d --build lab-target

say "Waiting for Jenkins"
for i in $(seq 1 60); do
  code="$(curl -s -o /dev/null -w '%{http_code}' http://localhost:8080/login || true)"
  [ "$code" = "200" ] && break
  [ "$i" = 60 ] && fail "Jenkins did not start. Check: docker logs secureship-jenkins"
  sleep 4
done

cat <<EOF

  ✔ SecureShip lab is running

  Jenkins     http://localhost:8080   user: $(get_env JENKINS_ADMIN_ID)   password: $(get_env JENKINS_ADMIN_PASSWORD)
  SonarQube   http://localhost:9000   user: admin   password: (SONAR_ADMIN_PASSWORD in ci/.env)
  ShopPilot   http://localhost:8088   (after the first successful deployment)

  Next: open Jenkins → job "SecureShip" → "Build Now".
  The first run registers the build parameters; later runs show "Build with Parameters".
  Repo used for the pipeline: $(get_env SECURESHIP_REPO_URL)
  Application repo:           $(get_env APP_REPO_URL)  (credential: $(get_env APP_GIT_CREDENTIALS_ID 2>/dev/null || true))

EOF
